-- tests/test_persona.lua
-- A counter is only live once it has real coords.
check('a placed counter is placed', Shops.isPlaced({ coords = vector3(1.0, 2.0, 3.0) }))
check('a SPOT placeholder is not placed', not Shops.isPlaced({ coords = vector3(0.0, 0.0, 0.0) }))
check('a counter with no coords is not placed', not Shops.isPlaced({}))
check('no counter at all is not placed', not Shops.isPlaced(nil))

local rox = Shops.counterById(Config, 'rox_baitshop')
eq('roxwood counter speaks roxwood', Shops.personaKey(rox), 'roxwood')
local sandy = Shops.counterById(Config, 'sandy_247')
eq('sandy 24/7 is a quickie', Shops.personaKey(sandy), 'quickie')
eq('explicit persona wins', Shops.personaKey({ region = 'roxwood', kind = 'quickie', persona = 'guncounter' }), 'guncounter')
eq('roxwood alarm goes to rpd', Shops.alarmDepartments('roxwood', Config)[1], 'rpd')
eq('unknown region falls back to ls set', Shops.alarmDepartments('moon', Config)[1], 'police')
eq('regionOf reads the counter region', Shops.regionOf(sandy), 'sandy')
local p = Shops.persona(sandy, Config)
local a, b = Shops.pedFor(p, 'sandy_247', 0), Shops.pedFor(p, 'sandy_247', 0)
eq('same counter same clerk', a, b)
check('ped is from the persona list', a == p.peds[1] or a == p.peds[2])
eq('boutique never fights', Config.Personas.boutique.weapon, nil)
eq('pedFor on a persona with no peds returns nil', Shops.pedFor({}, 'sandy_247', 0), nil)
eq('personaKey(nil) falls back to quickie', Shops.personaKey(nil), 'quickie')
